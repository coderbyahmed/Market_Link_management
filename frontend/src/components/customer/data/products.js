  products.find((product) => product.id === productId) || null;

const getApprovedProducts = () =>
  products.filter((product) => product.status === "approved");

const getFeaturedProducts = (limit = 8) =>
  getApprovedProducts().filter((product) => product.featured).slice(0, limit);

const getFreshProducts = (limit = 8) =>
  getApprovedProducts().filter((product) => product.fresh).slice(0, limit);

